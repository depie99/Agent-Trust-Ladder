import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { proposeAction, decideProposal, authorizeAction } from "../runtime/lib/approvals.mjs";
import { createBackup, previewRestore, scheduledBackup } from "../runtime/lib/backup.mjs";
import { acquireLease, reconcileLeases } from "../runtime/lib/leases.mjs";
const root = fs.mkdtempSync(path.join(os.tmpdir(), "atl-final-demo-"));
fs.mkdirSync(path.join(root, ".trust", "manager"), { recursive: true });
fs.writeFileSync(path.join(root, ".trust", "manager", "state.json"), JSON.stringify({ version: 1, revision: 1, tasks: {}, log: [] }));
const denied = proposeAction(root, { project: "p", task: "t", operation: "external", target: "x", args: { a: 1 } });
decideProposal(root, denied.id, "deny", { principal: "owner" });
assert.equal(authorizeAction(root, { project: "p", task: "t", operation: "external", target: "x", args: { a: 1 } }).allowed, false);
const lease = acquireLease(root, { project: "p", task: "t", role: "rowan" });
assert.equal(reconcileLeases(root).sessions.find((entry) => entry.id === lease.id).generation, lease.generation);
const backup = createBackup(root, { label: "demo" }); assert.equal(previewRestore(root, backup.id).verified, true);
assert.equal(scheduledBackup(root, { intervalHours: 24 }).created, false);
fs.rmSync(root, { recursive: true, force: true });
console.log("PASS: denied approval, lease recovery, backup integrity, and scheduled dedup demonstrations");
