import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { promoteSkill, registerRoutine } from "../runtime/lib/governance.mjs";
import { runRoutine, schedulerTick, listRoutineRuns } from "../runtime/lib/routines.mjs";
const root = fs.mkdtempSync(path.join(os.tmpdir(), "atl-routines-")); const skill = { id: "audit", version: "1", input_contract: "repo", validation: "checks", approval_boundary: "owner", rollback: "disable", fixtures: ["f"], capabilities: ["repo.read"], validation_evidence: { runs: [{ result: "pass", artifact_hash: "h" }], independent_review: { verdict: "approve" } } }; promoteSkill(root, skill); registerRoutine(root, { id: "nightly", project: "p", skill_id: "audit", skill_version: "1", schedule: "cron", idempotency_key: "source", retry_limit: 2 }); const store = JSON.parse(fs.readFileSync(path.join(root, ".trust", "manager", "brain", "skills.json"), "utf8")); assert.equal(store.skills.length, 1); assert.throws(() => runRoutine(root, "nightly", { sourceFingerprint: "x" }), /disabled/);
const routinesFile = path.join(root, ".trust/manager/brain/routines.json");
const routines = JSON.parse(fs.readFileSync(routinesFile, "utf8"));
routines.routines[0].enabled = true;
routines.routines[0].schedule = "* * * * *";
fs.writeFileSync(routinesFile, JSON.stringify(routines));
const now = new Date("2026-10-28T20:00:00Z");
runRoutine(root, "nightly", { sourceFingerprint: "x", now });
assert.equal(runRoutine(root, "nightly", { sourceFingerprint: "x", dryRun: false, now }).duplicate, false, "preview cannot suppress execution");
assert.equal(runRoutine(root, "nightly", { sourceFingerprint: "x", dryRun: false, now }).duplicate, true);
const tick = schedulerTick(root, { now, sourceFingerprint: "stable" });
assert.equal(tick.created.length, 1);
assert.ok(listRoutineRuns(root).some((run) => run.id === tick.created[0].id), "created run survives reload");
assert.equal(schedulerTick(root, { now, sourceFingerprint: "stable" }).created.length, 0, "same occurrence is deduplicated");
assert.equal(schedulerTick(root, { now: new Date(now.getTime() + 60000), sourceFingerprint: "stable" }).created.length, 1, "recurrence is distinct even with unchanged source");
routines.routines.unshift({ ...routines.routines[0], id: "bad-schedule", schedule: "invalid" });
fs.writeFileSync(routinesFile, JSON.stringify(routines));
const later = new Date(now.getTime() + 120000);
assert.equal(schedulerTick(root, { now: later }).created.length, 1, "invalid routine cannot suppress a valid neighbor");
assert.equal(listRoutineRuns(root).filter((run) => run.routine_id === "bad-schedule").length, 1);
schedulerTick(root, { now: later });
assert.equal(listRoutineRuns(root).filter((run) => run.routine_id === "bad-schedule").length, 1, "unchanged configuration failure is not retried");
routines.routines.shift();
const runFile = path.join(root, ".trust/manager/routine-runs.json");
const runs = JSON.parse(fs.readFileSync(runFile, "utf8"));
runs.runs[0].status = "failed"; runs.runs[0].next_retry_at = now.toISOString();
fs.writeFileSync(runFile, JSON.stringify(runs));
routines.routines[0].enabled = false; fs.writeFileSync(routinesFile, JSON.stringify(routines));
assert.equal(schedulerTick(root, { now }).created.length, 0, "disabled routines do not retry");
fs.writeFileSync(runFile, "corrupt");
assert.throws(() => schedulerTick(root, { now }), SyntaxError, "corrupt state is not silently discarded");
assert.equal(fs.readFileSync(runFile, "utf8"), "corrupt");
fs.rmSync(root, { recursive: true, force: true }); console.log("PASS: routines require approved skills, remain disabled, and preserve idempotency records");
