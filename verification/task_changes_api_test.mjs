import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import { fixture } from "./fixtures/task-changes/project.mjs";
import { startControlPlaneServer } from "../runtime/lib/control-plane-server.mjs";
import { digest } from "../runtime/lib/task-changes.mjs";
import { taskReviewReport } from "../runtime/lib/command-console.mjs";
import { createPluginHost, pluginTools } from "../runtime/lib/plugin-host.mjs";

const f = fixture(); f.edit();
const running = await startControlPlaneServer(f.root);
try {
  const page = await fetch(running.url), html = await page.text();
  const cookie = page.headers.get("set-cookie").split(";")[0], csrf = html.match(/name="atl-csrf" content="([^"]+)"/)[1];
  const headers = { cookie, "x-atl-csrf": csrf, "content-type": "application/json" };
  const get = (route) => fetch(`${running.url}${route}`, { headers });
  assert.match(html, /control-plane-changes\.js/);
  assert.equal((await fetch(`${running.url}api/task-changes?taskId=T-001`)).status, 403);
  const before = fs.readFileSync(path.join(f.root, ".trust/manager/state.json"), "utf8");
  const empty = await (await get("api/task-changes?taskId=T-001")).json();
  assert.equal(empty.availability, "capture_required");
  assert.equal(fs.existsSync(path.join(f.root, ".trust/manager/change-reviews")), false, "GET does not publish captures");
  const response = await fetch(`${running.url}api/task-changes/capture`, { method: "POST", headers, body: JSON.stringify({ task_id: "T-001" }) });
  const captured = await response.json(); assert.equal(response.status, 200, JSON.stringify(captured));
  assert.equal(captured.status, "blocked"); assert.equal(captured.total_files, 5);
  // Change profile: bounded line counts land on the page; binary/redacted stay null.
  assert.equal(captured.additions, 2); assert.equal(captured.deletions, 2);
  assert.equal(captured.stats_complete, false, "binary and redacted files have no line counts");
  const example = captured.files.find((file) => file.path === "runtime/example.js");
  assert.equal(example.additions, 1); assert.equal(example.deletions, 1);
  assert.equal(captured.files.find((file) => file.path === ".env").additions, null);
  assert.equal(captured.workspace, f.workspace); assert.equal(captured.repository, null);
  const diff = await (await get(`api/task-change-diff?taskId=T-001&changeSetId=${captured.id}&fileId=${digest("runtime/example.js")}`)).json();
  assert.equal(diff.availability, "available"); assert.match(diff.patch, /after/);
  assert.match(taskReviewReport(f.root, "T-001"), /runtime\/example\.js/);
  assert.match(taskReviewReport(f.root, "T-001", "mermaid"), /^flowchart LR/);
  assert.equal((await fetch(`${running.url}api/task-review-state?taskId=T-001`)).status, 403, "review state requires owner session");
  const reviewUrl = `${running.url}api/task-review-state`;
  let review = await (await get("api/task-review-state?taskId=T-001")).json();
  assert.equal(review.revision, 0);
  const put = (value) => fetch(reviewUrl, { method: "PUT", headers, body: JSON.stringify({ task_id: "T-001", change_set_id: captured.id, expected_revision: review.revision, ...value }) });
  let saved = await put({ action: "comment", file_id: example.id, side: "new", line: 1, text: "Review this captured line" });
  review = await saved.json(); assert.equal(saved.status, 200, JSON.stringify(review)); assert.equal(review.revision, 1); assert.equal(review.comments[0].change_set_id, captured.id);
  saved = await fetch(reviewUrl, { method: "PUT", headers, body: JSON.stringify({ task_id: "T-001", change_set_id: captured.id, expected_revision: 0, action: "reviewed", file_id: example.id }) });
  assert.equal(saved.status, 409, "stale optimistic revision is rejected");
  saved = await put({ action: "reviewed", file_id: example.id });
  review = await saved.json(); assert.equal(review.revision, 2); assert.equal(review.reviewed_files[0].change_set_id, captured.id);
  saved = await put({ action: "comment", file_id: example.id, side: "new", line: 999, text: "invalid anchor" });
  assert.equal(saved.status, 409, "line anchor is checked against the pinned diff");
  const concurrent = await Promise.all([0, 1].map(() => fetch(reviewUrl, { method: "PUT", headers, body: JSON.stringify({ task_id: "T-001", change_set_id: captured.id, expected_revision: 2, action: "reviewed", file_id: example.id, reviewed: false }) })));
  assert.deepEqual(concurrent.map((response) => response.status).sort(), [200, 409], "concurrent saves cannot overwrite each other");
  f.write("runtime/example.js", "const message is now newer\n");
  const newer = await (await fetch(`${running.url}api/task-changes/capture`, { method: "POST", headers, body: JSON.stringify({ task_id: "T-001" }) })).json();
  assert.notEqual(newer.id, captured.id);
  review = await (await get("api/task-review-state?taskId=T-001")).json();
  assert.equal(review.comments[0].change_set_id, captured.id, "older comments stay pinned to their historical capture");
  saved = await put({ action: "reply", file_id: example.id, comment_id: review.comments[0].id, text: "A reply" });
  review = await saved.json(); assert.equal(saved.status, 200); assert.equal(review.comments[0].replies[0].text, "A reply");
  const wrongCapture = await fetch(reviewUrl, { method: "PUT", headers, body: JSON.stringify({ task_id: "T-001", change_set_id: newer.id, expected_revision: review.revision, action: "reply", file_id: example.id, comment_id: review.comments[0].id, text: "wrong revision" }) });
  assert.equal(wrongCapture.status, 404, "replies cannot cross captured revisions");
  const lock = path.join(f.root, ".trust/manager/change-reviews/T-001/review-state.json.lock");
  fs.writeFileSync(lock, JSON.stringify({ pid: 2147483646, token: "dead-fixture-owner", at: Date.now() - 2000 }));
  saved = await put({ action: "resolve", file_id: example.id, comment_id: review.comments[0].id });
  review = await saved.json(); assert.equal(saved.status, 200); assert.equal(review.comments[0].resolved, true, "a dead lock owner cannot permanently block review saves");
  saved = await put({ action: "reopen", file_id: example.id, comment_id: review.comments[0].id });
  review = await saved.json(); assert.equal(saved.status, 200); assert.equal(review.comments[0].resolved, false);
  saved = await put({ action: "resolve", file_id: "foreign", comment_id: review.comments[0].id });
  assert.equal(saved.status, 404, "resolution anchors cannot cross files");
  const unpinned = await fetch(reviewUrl, { method: "PUT", headers, body: JSON.stringify({ task_id: "T-001", expected_revision: review.revision, action: "reviewed", file_id: example.id }) });
  assert.equal(unpinned.status, 400, "writes must explicitly pin the capture");
  const oldReport = JSON.parse(taskReviewReport(f.root, "T-001", "json", { captureId: captured.id }));
  assert.equal(oldReport.capture.id, captured.id);
  assert.ok(oldReport.graph.nodes.filter((node) => node.kind === "file").every((node) => node.capture_id === captured.id), "historical CLI reports use the same capture in files and graph");
  const cli = execFileSync(process.execPath, [fileURLToPath(new URL("../runtime/atl-manager.mjs", import.meta.url)), "review", "T-001", "--capture", captured.id, "--expand", "--file", example.id, "--json"], { cwd: f.root, env: { ...process.env, ATL_PROJECT: f.root }, windowsHide: true, encoding: "utf8", timeout: 15000 });
  assert.equal(JSON.parse(cli).nodes[0].kind, "hunk");
  const host = createPluginHost();
  try {
    assert.equal(pluginTools.find((tool) => tool.name === "atl_review").readOnly, true);
    const inspected = await host.call("atl_review", { project: f.root, taskId: "T-001", captureId: captured.id, fileId: example.id, expand: true, format: "json" });
    assert.equal(JSON.parse(inspected.content).capture_id, captured.id);
    assert.equal(host.serverGeneration, 0, "inspection does not start a daemon");
  } finally { await host.close(); }
  assert.equal((await get(`api/task-change-diff?taskId=T-001&changeSetId=${captured.id}&fileId=foreign`)).status, 404);
  assert.equal((await get("api/task-changes?taskId=T-001&changeSetId=..%2Foutside")).status, 400);
  assert.equal((await get("api/task-changes?taskId=T-999")).status, 404);
  const snapshot = await (await get("api/snapshot")).json();
  assert.doesNotMatch(JSON.stringify(snapshot), /change-reviews|--- a\/|const message = 'after'/, "periodic snapshot carries no source patch");
  const refused = await fetch(`${running.url}api/task-changes/capture`, { method: "POST", headers: { ...headers, origin: "https://foreign.example" }, body: JSON.stringify({ task_id: "T-001" }) });
  assert.equal(refused.status, 403);
  assert.equal(fs.readFileSync(path.join(f.root, ".trust/manager/state.json"), "utf8"), before);
} finally { await new Promise((resolve) => running.server.close(resolve)); f.cleanup(); }
console.log("PASS: task changes API — owner protection, lazy reads, capture and pinned diffs");
