import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { EventEmitter } from "node:events";
import { PassThrough } from "node:stream";
import { createAssistant, assistantContext, assistantGuidance, assistantWorkspace } from "../runtime/lib/control-assistant.mjs";
import { emptyState, saveState, loadState } from "../runtime/lib/state.mjs";
import { inspectHandoffChain } from "../runtime/lib/handoffs.mjs";
import { startControlPlaneServer } from "../runtime/lib/control-plane-server.mjs";
import { readRunLock } from "../runtime/lib/launch.mjs";

const root = fs.mkdtempSync(path.join(os.tmpdir(), "atl-assistant-"));
try {
  const state = emptyState();
  state.tasks["T-001"] = { id: "T-001", title: "Legacy", status: "done", completion_checks: ["check"], evidence: [] };
  const workspace = path.join(root, ".trust/manager/workspaces/T-002"); fs.mkdirSync(workspace, { recursive: true });
  state.tasks["T-002"] = { id: "T-002", title: "Blocked", status: "blocked", workspace, plan_depends_on: ["T-001"], blocker: { reason: "missing handoff" }, completion_checks: [] };
  state.tasks["T-002"].execution_budget = { used: 2, max_sessions: 4 };
  state.tasks["T-002"].recovery_records = [{ cause: "environment", reason: "missing tool", status: "waiting", recovery_owner: "mira", attempts: [{ action: "probe", status: "failed", preflight: { ready: false, reason: "tool still missing" } }] }];
  state.tasks["T-002"].evidence = [{ kind: "check", result: "pass", invalidated: true, code_revision: "old" }];
  saveState(root, state);
  const proposal = inspectHandoffChain(root, state.tasks["T-002"], state.tasks);
  assert.equal(proposal.ready, false); assert.equal(proposal.items[0].handoff, "legacy");
  assert.match(proposal.items[0].reason, /revalidation/);
  assert.equal(assistantContext(root, "T-002").dependencies[0].id, "T-001");
  assert.equal(assistantContext(root, "T-002").handoffs[0].handoff, "legacy");
  assert.throws(() => assistantContext(root, "../secret"), /Invalid/);
  const context = assistantContext(root, "T-002");
  assert.equal(context.execution_budget.remaining, 2);
  assert.equal(context.recovery_history[0].attempts[0].preflight.ready, false);
  assert.equal(context.evidence[0].invalidated, true);
  assert.equal(context.guidance.kind, "blocker");
  assert.match(context.guidance.suggested_message, /T-002/);
  assert.equal(assistantGuidance("T-002", { ...state.tasks["T-002"], plan_depends_on: ["T-999"] }, state, context.recovery_plan).kind, "prerequisite");
  assert.equal(assistantGuidance("T-002", { ...state.tasks["T-002"], plan_depends_on: [] }, state, { packet_revision: 2, checks: [{ check: "node verify.mjs", result: "fail" }], issues: [] }).kind, "failed-check");
  assert.equal(assistantGuidance("T-002", { ...state.tasks["T-002"], plan_depends_on: [], execution_budget: { used: 4, max_sessions: 4 }, status: "queued" }, state, { checks: [], issues: [] }).kind, "budget");
  assert.equal(assistantContext(root, "global").queue[0].id, "T-002");
  let child; let capturedArgs; let capturedPrompt = "";
  const launch = (_command, args) => { capturedArgs = args; capturedPrompt = ""; child = new EventEmitter(); child.stdin = new PassThrough(); child.stdin.on("data", (chunk) => { capturedPrompt += chunk.toString(); }); child.stdout = new PassThrough(); child.stderr = new PassThrough(); child.kill = () => { child.emit("close", null); }; return child; };
  const assistant = createAssistant(root, { launch, providerConfig: () => ({ selected: "configured" }), providerStatus: (config) => { assert.equal(config.selected, "configured"); return [{ id: "codex", command: "codex", installed: true, signedIn: true, defaultModel: "model-1", models: [{ id: "model-1" }] }]; }, discover: () => ({ available: true, path: "codex" }) });
  assert.throws(() => assistant.start({ scope: "global", provider: "codex", model: "model-1", message: "api_key=secret123" }), /secrets/);
  assert.throws(() => assistant.start({ scope: "global", provider: "codex", model: "unknown", message: "Explain" }), /available provider model/);
  assistant.start({ scope: "T-002", provider: "codex", model: "model-1", message: "Explain the blocker" });
  assert.ok(capturedArgs.includes("read-only"));
  assert.match(capturedPrompt, /context\.guidance as a hypothesis/);
  assert.match(capturedPrompt, /"kind":"blocker"/);
  assert.throws(() => assistant.start({ scope: "global", provider: "codex", model: "model-1", message: "Another" }), /active/);
  child.stdout.write("Diagnosis"); assert.equal(assistant.read("T-002").output, "Diagnosis");
  child.emit("close", 0); assert.equal(assistant.read("T-002").messages.at(-1).text, "Diagnosis");
  const restarted = createAssistant(root); assert.equal(restarted.read("T-002").status, "complete");
  assistant.start({ scope: "T-002", provider: "codex", model: "model-1", message: "Stop this" });
  assistant.cancel("T-002"); assert.equal(assistant.read("T-002").status, "cancelled");
  assert.throws(() => assistant.cancel("T-002"), /No active/);
  assistant.start({ scope: "T-002", provider: "codex", model: "model-1", message: "Continue" });
  child.stdout.write("Continued"); child.emit("close", 0);
  assert.equal(assistant.read("T-002").status, "complete", "a cancelled session must not mark a later successful message cancelled");
  assert.throws(() => assistant.start({ scope: "global", provider: "codex", model: "model-1", message: "Fix", mode: "fix" }), /task.*workspace/i);
  assert.throws(() => assistant.start({ scope: "T-002", provider: "codex", model: "model-1", message: "Fix", mode: "fix", workspace: root }), /workspace changed/);
  assistant.start({ scope: "T-002", provider: "codex", model: "model-1", message: "Fix this", mode: "fix", workspace: assistantWorkspace(root, "T-002") });
  assert.ok(capturedArgs.includes("workspace-write"));
  assert.equal(readRunLock(root).queueId, "assistant-T-002");
  child.stdout.write("Changes ready for review"); child.emit("close", 0);
  assert.equal(assistant.read("T-002").status, "awaiting-review", "provider exit is not review approval");
  assert.equal(readRunLock(root), null, "workspace lock is released after provider exit");
  assistant.start({ scope: "T-002", provider: "codex", model: "model-1", message: "Fix again", mode: "fix", workspace: assistantWorkspace(root, "T-002") });
  child.stderr.write("OpenAI Codex v1\nsandbox: read-only\n");
  assert.equal(assistant.read("T-002").status, "failed", "a read-only startup stops the provider immediately");
  child.emit("close", 0);
  assert.equal(assistant.read("T-002").status, "failed", "a read-only effective sandbox cannot be reported as a fix");
  assert.equal(loadState(root).tasks["T-002"].execution_budget.used, 4, "fix sessions consume the durable task allowance");
  assert.throws(() => assistant.start({ scope: "T-002", provider: "codex", model: "model-1", message: "Fix again", mode: "fix", workspace: assistantWorkspace(root, "T-002") }), /allowance exhausted/);
  assert.equal(readRunLock(root), null);
  const running = await startControlPlaneServer(root);
  try {
    const diagnosis = await fetch(`${running.url}api/assistant`, { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ action: "read", scope: "T-002" }) }).then((response) => response.json());
    assert.equal(diagnosis.recovery.task_id, "T-002");
    assert.equal(diagnosis.recovery.retry_ready, false);
    assert.equal(diagnosis.guidance.kind, "budget", "guidance reflects the latest persisted task budget");
    const recovery = await fetch(`${running.url}api/task-recovery?taskId=T-002`).then((response) => response.json());
    assert.equal(recovery.proposal.items[0].handoff, "legacy");
    const response = await fetch(`${running.url}api/assistant`, { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ action: "send", scope: "T-002", provider: "codex", model: "model-1", message: "Diagnose this task" }) });
    const pending = await response.json();
    assert.equal(response.status, 202);
    assert.equal(pending.approvalRequired, true, "no provider starts before the owner grants the exact request");
    const fix = await fetch(`${running.url}api/assistant`, { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ action: "send", scope: "T-002", provider: "codex", model: "model-1", message: "Fix this", mode: "fix" }) }).then((response) => response.json());
    assert.equal(fix.approvalRequired, true);
    assert.equal(fix.proposal.action.operation, "assistant.fix");
    assert.equal(fix.proposal.action.args.workspace, assistantWorkspace(root, "T-002"));
    assert.equal(fs.existsSync(path.join(root, ".trust/manager/assistant/T-002.json")), true, "previous test transcript remains local");
  } finally { await new Promise((resolve) => running.server.close(resolve)); }
  console.log("PASS: legacy handoff inventory and bounded assistant sessions");
} finally { fs.rmSync(root, { recursive: true, force: true }); }
