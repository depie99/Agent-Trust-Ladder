import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { chromium } from "playwright";
import { promoteSkill } from "../runtime/lib/governance.mjs";
import { createRecord } from "../runtime/lib/research.mjs";
import { addClaim, listClaims } from "../runtime/lib/brain.mjs";
import { emptyState, saveState } from "../runtime/lib/state.mjs";
import { startControlPlaneServer } from "../runtime/lib/control-plane-server.mjs";
const root = fs.mkdtempSync(path.join(os.tmpdir(), "atl-knowledge-"));
let server, browser;
try {
  fs.mkdirSync(path.join(root, "config"), { recursive: true });
  fs.writeFileSync(path.join(root, "config", "manager.json"), JSON.stringify({ version: 1 }));
  saveState(root, emptyState());
  createRecord(root, { title: "First retrospective", priority: "P1", kind: "retro", concepts: ["retrospective"], atl_impact: "Check dependencies", evidence: "second-hand" });
  createRecord(root, { title: "Second retrospective", priority: "P1", kind: "retro", concepts: ["retrospective"], atl_impact: "Inspect logs", evidence: "second-hand" });
  assert.deepEqual(listClaims(root).map(c => c.status), ["PARTIAL", "PARTIAL"]);
  addClaim(root, { text: "Legacy flag", source_id: "legacy", source_content: "source", subject: "retrospective", status: "CONFLICTED" });
  ({ server, url: globalThis.testUrl } = await startControlPlaneServer(root));
  browser = await chromium.launch({ headless: true });
  const page = await browser.newPage({ viewport: { width: 1280, height: 900 } });
  await page.goto(globalThis.testUrl);
  await page.locator('[data-page="brain"]').first().click();
  await page.getByText("Legacy flag", { exact: true }).waitFor();
  assert.equal(await page.getByText("1 flagged for comparison", { exact: true }).count(), 1);
  assert.equal(await page.getByText("Not reviewed yet", { exact: true }).count(), 3);
  assert.equal(await page.getByRole("button", { name: "Approve claim" }).count(), 2);
  await page.getByRole("button", { name: "Register a routine" }).click();
  assert.equal(await page.getByText("Add a skill to the Gold list", { exact: false }).count(), 1);
  await page.getByRole("button", { name: "Cancel" }).click();
  await page.getByRole("button", { name: "Review installed skills" }).click();
  assert.ok(await page.locator("#brainSkillChoice option").count() > 0);
  assert.equal(await page.getByText("Independent verification unavailable", { exact: true }).count(), 1);
  assert.equal(await page.getByRole("button", { name: /promote skill/i }).count(), 0);
  const rejected = await page.evaluate(async () => { const response = await fetch("/api/brain", { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ action: "promote-skill", skill: {} }) }); return response.status; });
  assert.equal(rejected, 409);
  await page.getByRole("button", { name: "Close", exact: true }).click();
  promoteSkill(root, { id: "summary", version: "1.0.0", input_contract: "research", validation: "fixture run", approval_boundary: "manager", rollback: "disable", fixtures: ["fixture-1"], capabilities: ["repo.read"], validation_evidence: { runs: [{ result: "pass", artifact_hash: "abc123" }], independent_review: { verdict: "approve", reviewer: "reviewer" } } });
  await page.getByRole("button", { name: "Refresh", exact: true }).click();
  await page.getByText("summary", { exact: true }).waitFor();
  await page.getByRole("button", { name: "Register a routine" }).click();
  await page.locator("#brainRoutineId").fill("daily");
  await page.getByRole("button", { name: "Save disabled routine" }).click();
  await page.getByText("daily", { exact: true }).waitFor();
  const saved = JSON.parse(fs.readFileSync(path.join(root, ".trust/manager/brain/routines.json"), "utf8")).routines[0];
  assert.equal(saved.project, "atl"); assert.equal(saved.schedule, "0 9 * * *"); assert.equal(saved.enabled, false); assert.equal(saved.skill_id, "summary");
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, "mobile page must not overflow horizontally");
  console.log("PASS: research topics do not create false conflicts; knowledge page explains legacy flags and reflows");
} finally { if (browser) await browser.close(); if (server) await new Promise(resolve => server.close(resolve)); fs.rmSync(root, { recursive: true, force: true }); }
