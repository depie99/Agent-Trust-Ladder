import fs from "node:fs";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { buildShowMe, changedFileList } from "./show-me.mjs";

function git(root, args) {
  try {
    return execFileSync("git", args, { cwd: root, encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }).trim();
  } catch {
    return "";
  }
}

function slug(value) {
  return String(value || "change").toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "").slice(0, 64) || "change";
}

function outline(files) {
  if (!files.length) return "| Area | Files |\n| --- | --- |\n| None detected | — |";
  const groups = new Map();
  for (const file of files.filter((entry) => !entry.startsWith(".humanlayer/tasks/"))) {
    const area = file.startsWith("runtime/") ? "Runtime" : file.startsWith("skills/") ? "Skills" : file.startsWith("docs/") ? "Docs" : file.startsWith("config/") ? "Configuration" : "Project surface";
    if (!groups.has(area)) groups.set(area, []);
    groups.get(area).push(file);
  }
  const compact = [...groups.entries()].map(([area, entries]) => {
    const ordered = [...entries].sort((a, b) => a.length - b.length || a.localeCompare(b));
    const visible = ordered.slice(0, 3).map((entry) => `\`${entry}\``);
    const hidden = ordered.length - visible.length;
    if (hidden > 0) visible.push(`+${hidden} supporting`);
    return `| ${area} | ${entries.length} | ${visible.join(", ")} |`;
  });
  return ["| Area | Count | Key files |", "| --- | ---: | --- |", ...compact, "", `_${files.length} changed files collapsed into responsibility groups; key files are shown first._`].join("\n");
}

function architectureView(files) {
  if (files.some((file) => file.includes("memory.mjs"))) {
    return [
      "flowchart LR",
      "  U[ATL request] --> R[atl-manager]",
      "  R --> T[triage]",
      "  T --> Q[Mem0 recall]",
      "  R --> S[Show Me]",
      "  R --> P[Visual PR]",
      "  B[Beacon verifies done] --> W[Mem0 add outcome]",
      "  W -. optional .-> G[(Graph store)]",
      "  R --> A[(state.json + feed.jsonl)]",
      "  Q -. advisory .-> T",
    ].join("\n");
  }
  return "flowchart LR\n  U[ATL request] --> R[route] --> W[work] --> V[verify] --> A[(state + feed)]";
}

function capabilitySummary(files) {
  const has = (fragment) => files.some((file) => file.includes(fragment));
  const items = [];
  if (has("atl-content-quality")) {
    items.push("**Content quality team** — adds a bounded intake, rubric, readability/SEO checks, and a delivery handoff for content changes.");
  }
  if (has("atl-team") || has("atl-manager.mjs")) {
    items.push("**Team routing** — makes role selection, triage, independent review, and evidence-gated completion visible through the manager workflow.");
  }
  if (has("show-me.mjs")) {
    items.push("**Show Me** — emits a structural handoff with capability map, architecture, control flow, and evidence snapshot for human review.");
  }
  if (has("visual-pr.mjs")) {
    items.push("**Visual PR** — generates this description from the inspected diff, including a grouped file map, architecture diagram, and task-state boundary.");
  }
  if (has("memory.mjs")) {
    items.push("**Optional graph memory** — recalls advisory context during triage and records verified outcomes after completion; Mem0 is opt-in and never authoritative.");
  }
  return items.length ? items.map((item) => `- ${item}`).join("\n") : "- No capability summary was inferred from the inspected files.";
}

function stateView(files) {
  if (!files.some((file) => file.includes("memory.mjs"))) return "stateDiagram-v2\n  [*] --> work\n  work --> verify\n  verify --> done";
  return [
    "stateDiagram-v2",
    "  [*] --> in_progress",
    "  in_progress --> in_review",
    "  in_review --> verifying",
    "  verifying --> done",
    "  done --> memory_written: optional Mem0 write",
    "  memory_written --> [*]",
    "  note right of memory_written: advisory context only",
  ].join("\n");
}

export function buildVisualPrDescription(root, { title = null, taskId = null } = {}) {
  const branch = git(root, ["branch", "--show-current"]) || "detached";
  const files = changedFileList(root);
  const effectiveTitle = title || `Change on ${branch}`;
  return [
    `<!-- Generated by ATL visual-pr from inspected repository output. Branch: ${branch} -->`,
    "",
    "## Why the change",
    "",
    `ATL adds a bounded content-quality and team-handoff workflow so reviewers can see the change shape and verify its evidence before trusting it.`,
    "",
    "## Special things to note",
    "",
    "- Mem0 graph memory is not enabled by default and does not replace ATL's authoritative state or audit feed.",
    "- The generated outline is a reviewer aid; runtime checks remain the source of behavioral proof.",
    "",
    "## Change outline",
    "",
    "### What this PR adds",
    "",
    capabilitySummary(files),
    "",
    "### Changed responsibilities",
    "",
    "```markdown",
    outline(files),
    "```",
    "",
    "### Architecture view",
    "",
    "```mermaid",
    architectureView(files),
    "```",
    "",
    "### Task-state boundary",
    "",
    "```mermaid",
    stateView(files),
    "```",
    "",
    "### Show Me artifact",
    "",
    "The generated structural handoff is saved beside this description as `show-me.md`; it is a review aid, not behavioral proof.",
    "",
    `Title: ${effectiveTitle}`,
    "",
  ].join("\n");
}

export function saveVisualPrDescription(root, { title = null, taskId = null, slug: requestedSlug = null } = {}) {
  const branch = git(root, ["branch", "--show-current"]) || "change";
  const dir = path.join(root, ".humanlayer", "tasks", `pr-${slug(requestedSlug || branch)}`);
  const file = path.join(dir, "description.md");
  const showMeFile = path.join(dir, "show-me.md");
  fs.mkdirSync(dir, { recursive: true });
  fs.writeFileSync(showMeFile, buildShowMe(root, { taskId }), "utf8");
  fs.writeFileSync(file, buildVisualPrDescription(root, { title, taskId }), "utf8");
  return file;
}
