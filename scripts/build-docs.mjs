// Markdown is the editable source. HTML, search, and Mermaid assets are generated.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import MarkdownIt from 'markdown-it';
import {compile} from 'sass';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const docs = path.join(root, 'docs');
const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
export const pages = JSON.parse(fs.readFileSync(path.join(docs, 'site.json'), 'utf8'));
export const slug = text => text.toLowerCase().replace(/<[^>]*>/g, '').replace(/[^\p{L}\p{N}\s_-]/gu, '').trim().replace(/\s/g, '-');
const escape = value => String(value).replace(/[&<>"']/g, c => ({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
const bySource = new Map(pages.map(p => [path.resolve(root, p.source), p.url]));
const changed = [];
function write(file, content) {
  const target = path.join(docs, file);
  if (fs.existsSync(target) && fs.readFileSync(target, 'utf8') === content) return;
  changed.push(file);
  if (!process.argv.includes('--check')) { fs.mkdirSync(path.dirname(target), {recursive:true}); fs.writeFileSync(target, content); }
}
const search = [];
write('site.css',compile(path.join(docs,'scss/styles.scss'),{sourceMap:false}).css+'\n');
for (const page of pages) {
  const source = fs.readFileSync(path.join(root, page.source), 'utf8');
  const toc = [], used = new Map();
  const md = new MarkdownIt({html:true, linkify:true, typographer:false});
  const fence = md.renderer.rules.fence;
  md.renderer.rules.fence = (tokens, i, options, env, self) => tokens[i].info.trim() === 'mermaid'
    ? `<figure class="diagram"><pre class="mermaid">${escape(tokens[i].content)}</pre><figcaption>Diagram source is available in this page’s Markdown.</figcaption></figure>`
    : `<div class="code-block"><button class="copy-code" type="button" aria-label="Copy code">Copy</button>${fence(tokens,i,options,env,self)}</div>`;
  md.core.ruler.push('docs-links-and-headings', state => {
    for (let i=0;i<state.tokens.length;i++) {
      const token = state.tokens[i];
      if (token.type === 'heading_open') {
        const text = state.tokens[i+1].content;
        const base = slug(text), count = used.get(base) || 0;
        used.set(base,count+1);
        const id = count ? `${base}-${count}` : base;
        token.attrSet('id',id);
        if (token.tag === 'h2' || token.tag === 'h3') toc.push({id,text,level:token.tag});
      }
      for (const child of token.children || []) {
        if (child.type !== 'link_open') continue;
        const href = child.attrGet('href');
        if (!href || /^(?:[a-z]+:|#|\/)/i.test(href)) continue;
        const [file,hash] = href.split('#');
        const absolute = path.resolve(path.dirname(path.join(root,page.source)),file);
        const mapped = bySource.get(absolute);
        if (mapped) child.attrSet('href',mapped+(hash ? '#'+hash : ''));
        else if (file.endsWith('.md') || !absolute.startsWith(docs+path.sep)) {
          child.attrSet('href',`https://github.com/depie99/Agent-Trust-Ladder/blob/main/${path.relative(root,absolute).replaceAll('\\','/')}${hash?'#'+hash:''}`);
        }
      }
    }
  });
  const article = md.render(source);
  const groups = [...new Set(pages.map(p => p.group))];
  const nav = groups.map(group => `<section class="nav-group"><h2>${escape(group)}</h2>${pages.filter(p=>p.group===group).map(p=>`<a href="${p.url}"${p.url===page.url?' aria-current="page"':''}>${escape(p.title)}</a>`).join('')}</section>`).join('');
  const index = pages.indexOf(page);
  const adjacent = [pages[index-1],pages[index+1]].map((p,i)=>p?`<a href="${p.url}"><small>${i?'Next':'Previous'}</small>${escape(p.title)}</a>`:'<span></span>').join('');
  const html = `<!doctype html>
<!-- Generated by scripts/build-docs.mjs from ${page.source}. Do not edit this HTML. -->
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1"><title>${escape(page.title)} · ATL Docs</title><meta name="description" content="${escape(page.description)}"><link rel="canonical" href="${escape(pkg.homepage+page.url)}"><link rel="icon" href="favicon.svg"><link rel="stylesheet" href="site.css"><script src="site.js" defer></script><script type="module" src="mermaid-loader.js"></script></head>
<body><a class="skip-link" href="#main-content">Skip to content</a><header class="site-header"><a class="brand" href="index.html"><span class="brand-mark">A</span> ATL <span>Documentation</span></a><div class="header-actions"><button id="menu-toggle" aria-expanded="false" aria-controls="sidebar">Menu</button><button id="search-open">Search <kbd>Ctrl K</kbd></button><button id="theme-toggle" aria-label="Toggle theme">Theme</button><a href="https://github.com/depie99/Agent-Trust-Ladder">GitHub ↗</a></div></header>
<div class="docs-layout"><aside id="sidebar" class="sidebar"><nav aria-label="Documentation">${nav}</nav><p class="version">Package ${escape(pkg.version)} · Node ${escape(pkg.engines.node)}<br>Source snapshot: October 29, 2026</p></aside><main id="main-content"><div class="breadcrumbs"><a href="index.html">Docs</a> / ${escape(page.group)}</div><article>${article}</article><nav class="adjacent" aria-label="Adjacent pages">${adjacent}</nav><footer><a href="https://github.com/depie99/Agent-Trust-Ladder/blob/main/${page.source}">View Markdown source ↗</a><a href="documentation.html">Improve this documentation</a><span>${escape(pkg.license)}</span></footer></main><aside class="page-toc"><h2>On this page</h2><nav aria-label="On this page">${toc.map(h=>`<a class="${h.level}" href="#${h.id}">${escape(h.text)}</a>`).join('')}</nav></aside></div>
<dialog id="search-dialog"><div class="search-heading"><label for="search-input">Search documentation</label><button id="search-close" aria-label="Close search">Esc</button></div><input id="search-input" type="search" placeholder="Try Jira, queue, Ask ATL, or models" autocomplete="off"><div id="search-results" aria-live="polite"></div></dialog></body></html>\n`;
  write(page.url,html);
  // One searchable record per section, including introductory text.
  const sections = source.split(/(?=^## )/m);
  for (const section of sections) {
    const heading = section.match(/^## (.+)/m)?.[1];
    search.push({title:page.title,heading:heading || page.description,url:page.url+(heading?'#'+slug(heading):''),text:section.replace(/```[\s\S]*?```/g,' ').replace(/<[^>]+>|[#*`|]/g,' ').replace(/\s+/g,' ').trim()});
  }
}
write('search-index.json',JSON.stringify(search,null,2)+'\n');
write('sitemap.xml','<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'+pages.map(page=>`  <url><loc>${escape(pkg.homepage+page.url)}</loc></url>`).join('\n')+'\n</urlset>\n');
write('robots.txt',`User-agent: *\nAllow: /\nSitemap: ${pkg.homepage}sitemap.xml\n`);
const vendorSource = path.join(root,'node_modules/mermaid/dist/mermaid.min.js');
if (!fs.existsSync(vendorSource)) throw new Error('Run npm ci before building documentation.');
write('vendor/mermaid.min.js',fs.readFileSync(vendorSource,'utf8'));
write('vendor/MERMAID-LICENSE',fs.readFileSync(path.join(root,'node_modules/mermaid/LICENSE'),'utf8'));
if (process.argv.includes('--check') && changed.length) { console.error('Stale generated documentation: '+changed.join(', ')); process.exitCode=1; }
else console.log(`${pages.length} documentation pages; ${search.length} searchable sections; ${changed.length} generated files ${process.argv.includes('--check')?'checked':'updated'}.`);
